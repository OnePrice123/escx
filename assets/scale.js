/* ─── Свод по театру ────────────────────────────────────
   Индекс театра = МИНИМУМ по диадам, не среднее.
   Театр настолько мирен, насколько мирна его самая горячая диада.

   Риск: связанность не повышает вероятность того, что рванёт где-то —
   она повышает вероятность того, что рванёт везде сразу.
     P(обе)      = ρ·min(r) + (1−ρ)·Πr
     P(хотя бы одна) = Σr − P(обе)
   ──────────────────────────────────────────────────────── */
function theatreRollup(th) {
  const ds = th.dyads.map(id => CONFLICTS[id]);
  const rs = ds.map(d => d.escalationRisk / 100);
  const p = ρ => {
    const both = ρ * Math.min(...rs) + (1 - ρ) * rs.reduce((a, b) => a * b, 1);
    return { both, any: Math.min(1, rs.reduce((a, b) => a + b, 0) - both) };
  };
  const { both, any } = p(th.coupling);
  return {
    index: Math.min(...ds.map(d => d.now)),
    weekAgo: Math.min(...ds.map(d => d.weekAgo)),
    monthAgo: Math.min(...ds.map(d => d.monthAgo)),
    hottest: ds.reduce((a, b) => (a.now <= b.now ? a : b)),
    riskAny: Math.round(any * 100),
    riskBoth: Math.round(both * 100),
    sourcesLive: ds.reduce((n, d) => n + d.sourcesLive, 0),
    eventsLast24h: ds.reduce((n, d) => n + d.eventsLast24h, 0),
    dyads: ds,
    /* слова и дела по театру: берём диаду с наибольшим по модулю расхождением —
       именно она и есть интересный случай */
    divergence: ds.map(d => d.divergence)
      .reduce((a, b) => (Math.abs(a.words - a.deeds) >= Math.abs(b.words - b.deeds) ? a : b)),
    divergenceOwner: ds.reduce((a, b) =>
      (Math.abs(a.divergence.words - a.divergence.deeds) >= Math.abs(b.divergence.words - b.divergence.deeds) ? a : b)),
    chokepoints: ds.flatMap(d => d.chokepoints || []),
  };
}

