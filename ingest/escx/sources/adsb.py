"""Военная авиация из открытой сети ADS-B.

ПОЧЕМУ НЕ FAA И НЕ КОММЕРЧЕСКИЕ ТРЕКЕРЫ. Официальные и коммерческие ленты
цензурируются: в США действует программа LADD, по которой владелец борта может
скрыть его из публичного показа, и крупные сервисы эти запросы исполняют.
Именно те борта, ради которых всё затевается — разведчики, заправщики,
правительственные рейсы, — оттуда и пропадают.

Нецензурируемые данные дают сети независимых приёмников. ADS-B Exchange был
такой сетью, но в 2023 году его купила JetNet, и часть сообщества ушла делать
форки. Берётся форк adsb.lol: те же данные, но без ключа, без карты и без
лимита в пятьсот запросов, за которым начинается платный тариф. Провайдер
вынесен в одну константу — если покрытие форка окажется хуже, переключение
стоит одной строки.

ЧЕГО ЭТОТ ИСТОЧНИК НЕ МОЖЕТ, и это надо знать до того, как строить на нём:

  * бэкфилла не существует в природе. Это снимок «кто в воздухе сейчас»,
    историю можно только накапливать;
  * покрытие неравномерно. Приёмники стоят там, где живут энтузиасты, поэтому
    над Европой видно всё, а над Чёрным морем и Тайваньским проливом почти
    ничего. Российские, китайские и корейские военные борта вдобавок часто
    не вещают вовсе;
  * отсутствие бортов в зоне НЕ означает отсутствия активности. Означает
    отсутствие наблюдения, и путать это нельзя.
"""
from __future__ import annotations
import json
import math
from ..http import get

API = "https://api.adsb.lol/v2/mil"

# Борта из списка LADD: те, чей владелец попросил скрыть их из публичного
# показа. Коммерческие ленты просьбу исполняют, независимые сети — нет, и это
# ровно та причина, по которой источник выбран такой. Отдельная ручка, потому
# что в /v2/mil они не попадают.
API_LADD = "https://api.adsb.lol/v2/ladd"

# Все борта вокруг точки — гражданские в том числе. Нужен НЕ для военных:
# им меряется НАБЛЮДАЕМОСТЬ зоны, см. zone_traffic. Радиус в морских милях.
API_POINT = "https://api.adsb.lol/v2/point/{lat}/{lon}/{radius}"
MAX_RADIUS_NM = 250

# Типы, по которым видно подготовку и наблюдение, а не рутину.
#
# Разведка (R135 — RC-135, RC12, U2, P8, RQ4/MQ4 — Global Hawk и Triton),
# самолёты ДРЛО (E3TF, E3CF), воздушные командные пункты (E6), заправщики
# (K35R, KC30) и стратегический транспорт (C17, A400, C130, C30J).
#
# Учебные, вертолёты и связные борта намеренно НЕ включены: их в выдаче
# большинство, они летают ежедневно и утопили бы сигнал в рутине.
SIGNIFICANT = {
    "R135", "RC12", "U2", "P8", "RQ4", "MQ4",       # разведка
    "E3TF", "E3CF", "E6",                            # ДРЛО и управление
    "K35R", "KC30", "KC46",                          # заправщики
    "C17", "A400", "C130", "C30J", "C5M",            # стратегический транспорт
}


def _aircraft(url: str) -> list[dict]:
    blob = get(url, use_cache=False)
    if not blob:
        return []
    try:
        d = json.loads(blob)
    except ValueError:
        return []
    return [a for a in (d.get("ac") or []) if a.get("lat") is not None]


def fetch_military() -> list[dict]:
    """Военные борта, которые сеть видит прямо сейчас.

    К военной ленте добавляются борта из LADD — те, что просили скрыть и что
    коммерческие ленты прячут. Ради них источник и выбирался, а в /v2/mil они
    не попадают. Склейка по hex: один борт может быть в обоих списках.
    """
    seen, out = set(), []
    for url in (API, API_LADD):
        for a in _aircraft(url):
            h = a.get("hex")
            if h and h in seen:
                continue
            if h:
                seen.add(h)
            out.append(a)
    return out


def zone_center_radius(box: list[float]) -> tuple[float, float, int]:
    """Центр прямоугольника и радиус в морских милях, покрывающий его.

    Одна точка вместо прямоугольника — упрощение, и оно осознанное: ручка
    источника принимает только круг, а мерить кругом мы будем не активность,
    а сам факт наблюдения. Для «видно ли тут вообще что-нибудь» центра зоны
    достаточно, и потолок в 250 миль этого не портит.
    """
    s, w, n, e = box
    lat, lon = (s + n) / 2, (w + e) / 2
    # Градус широты — 60 морских миль; по долготе — те же 60, сжатые косинусом.
    half_lat = (n - s) / 2 * 60
    half_lon = (e - w) / 2 * 60 * max(0.1, math.cos(math.radians(lat)))
    r = int(math.hypot(half_lat, half_lon))
    return round(lat, 4), round(lon, 4), max(10, min(MAX_RADIUS_NM, r))


def zone_traffic(box: list[float]) -> int:
    """Сколько бортов вообще видно в зоне — гражданских в том числе.

    Это и есть ответ на вопрос «наблюдается ли зона». Раньше на него отвечал
    счётчик военных бортов из той же ленты, и ответить он не мог в принципе:
    ноль военных над Тайванем означает и «военных нет», и «приёмников нет», а
    для индекса это противоположные вещи. Гражданский трафик их разделяет —
    он есть всюду, где есть приёмники.
    """
    lat, lon, r = zone_center_radius(box)
    return len(_aircraft(API_POINT.format(lat=lat, lon=lon, radius=r)))


def in_box(a: dict, box: list[float]) -> bool:
    s, w, n, e = box
    return s <= a["lat"] <= n and w <= a["lon"] <= e


def count_by_zone(aircraft: list[dict], zones: dict[str, dict]
                  ) -> dict[str, tuple[int, int]]:
    """{dyad_id: (всего бортов, из них значимых)}.

    Два числа, а не одно: общее показывает, наблюдается ли зона вообще, а
    значимое — есть ли там то, что относится к делу. Ноль значимых при десяти
    общих и ноль при нуле общих означают разное.
    """
    out: dict[str, tuple[int, int]] = {}
    for dyad_id, z in zones.items():
        box = z.get("box")
        if not box or len(box) != 4:
            continue
        ins = [a for a in aircraft if in_box(a, box)]
        sig = [a for a in ins if a.get("t") in SIGNIFICANT]
        out[dyad_id] = (len(ins), len(sig))
    return out
