"""Расчёт индикаторов и робастная нормализация.

Здесь реализована формула из раздела 4 методологии: медиана и MAD вместо среднего
и стандартного отклонения. Причина: у конфликтных рядов тяжёлые хвосты, одно
крупное событие сдвигает среднее так, что все последующие значения выглядят
нормальными. Медиана этого не делает.
"""
from __future__ import annotations
import math, statistics as st
from collections import defaultdict
from datetime import date, timedelta

MAD_K = 1.4826            # приводит MAD к масштабу стандартного отклонения

# Предел z-оценки. Робастный z в 174 не означает конец света — он означает, что
# опорная величина выродилась: при короткой истории MAD уходит в 0.00004, и любое
# ненулевое значение делится почти на ноль. Именно так Россия — Украина оказалась
# ровно на 100 при фазе 5 из 7. Обрезка ловит вырождение и не даёт одной паре
# с бедной историей упереть шкалу в потолок.
Z_CAP = 8.0

# Потолок ОТНОСИТЕЛЬНОГО накала. Верхние пять пунктов шкалы зарезервированы за
# абсолютным пределом — применением ядерного оружия (фаза 7). Смысл резерва в
# запасе хода: пара, у которой уже идёт война, обязана иметь куда расти, иначе
# ухудшение конфликта не отражается в числе вовсе. До правки Россия — Украина
# стояла на 100 и не могла сдвинуться ни при каком развитии событий.
HEAT_MAX = 95.0
WINSOR = (0.01, 0.99)


def winsorize(xs: list[float], lo: float = WINSOR[0], hi: float = WINSOR[1]) -> list[float]:
    """Обрезка хвостов по перцентилям.

    Индексы считаются от n-1 и зажимаются в границы — наивная формула
    int(n*lo)-1 при коротком ряде даёт -1 и обрезает всё до максимума.
    Такая ошибка не падает, а молча превращает ряд в константу.
    """
    if not xs:
        return []
    s = sorted(xs)
    n = len(s)
    ia = min(max(round(lo * (n - 1)), 0), n - 1)
    ib = min(max(round(hi * (n - 1)), 0), n - 1)
    a, b = s[ia], s[ib]
    if a > b:
        a, b = b, a
    return [min(max(x, a), b) for x in xs]


def robust_z(x: float, history: list[float]) -> float:
    """z-оценка по медиане и MAD. При вырожденной истории возвращает 0."""
    h = winsorize([v for v in history if v is not None])
    if len(h) < 8:
        return 0.0
    med = st.median(h)
    mad = st.median([abs(v - med) for v in h])
    if mad == 0:
        sd = st.pstdev(h)
        z = 0.0 if sd == 0 else (x - med) / sd
    else:
        z = (x - med) / (MAD_K * mad)
    return max(-Z_CAP, min(Z_CAP, z))


def rolling_counts(events: list[dict], day: date, window: int = 30) -> dict:
    """Кинетика за окно: число событий, погибшие, охват географии.

    Отбрасываются события с date_prec >= 3 (дата известна лишь до месяца/года):
    класть их в 30-дневное окно нельзя, они размажут сигнал по всему периоду.
    """
    lo = day - timedelta(days=window)
    n = fat = 0
    cells = set()
    for e in events:
        if (e.get("date_prec") or 1) >= 3:
            continue
        d = e.get("occurred_at")
        if not d:
            continue
        try:
            ed = date.fromisoformat(d[:10])
        except ValueError:
            continue
        if lo < ed <= day:
            n += 1
            fat += e.get("fatalities") or 0
            if e.get("lat") is not None and e.get("lon") is not None:
                cells.add((round(e["lat"] * 2) / 2, round(e["lon"] * 2) / 2))
    return {"events_30d": n, "fatalities_30d": fat, "geo_cells_30d": len(cells)}


def goldstein_weighted(events: list[dict]) -> float | None:
    """Средний Голдштейн, взвешенный на число упоминаний.

    Взвешивание обязательно: без него одно упоминание в блоге весит столько же,
    сколько сюжет, разошедшийся по тысяче изданий. Это прямое следствие того,
    что Голдштейн — атрибут типа события, а не измеренная интенсивность.
    """
    num = den = 0.0
    for e in events:
        g, m = e.get("goldstein"), e.get("num_mentions") or 1
        if g is not None:
            num += g * m
            den += m
    return (num / den) if den else None


def media_normalized(mentions_dyad: float, mentions_global: float) -> float | None:
    """Доля покрытия диады в мировом потоке — правило 5 методологии.

    Абсолютный объём упоминаний измеряет внимание прессы, а не риск. Нормировка
    на общий объём убирает эффект «крупные сюжеты всегда ярче».
    """
    if not mentions_global:
        return None
    return mentions_dyad / mentions_global


BLOCK_WEIGHTS = {
    "kinetic": 0.35, "military": 0.20, "diplomatic": 0.15,
    "economic": 0.15, "informational": 0.15,
}


# Слова и дела. Разделение то же, что в весах методологии: инфополе — это
# сообщения о конфликте, остальные четыре блока — то, что произошло.
# Дипломатия отнесена к делам намеренно: голосование в ГА ООН — записанное
# в протоколе действие, а не заявление о намерениях.
WORDS_BLOCKS = ("informational",)
DEEDS_BLOCKS = ("kinetic", "military", "economic", "diplomatic")

# Какая доля веса стороны должна быть измерена, чтобы сторону считать вообще.
MIN_SIDE_SHARE = 0.5


def side_heat(block_z: dict[str, float], blocks: tuple[str, ...],
              scale: float = 1.6) -> float | None:
    """Накал по части блоков, веса перенормированы внутри этой части.

    Без перенормировки сравнивать стороны нельзя: у слов вес 0.15, у дел 0.85,
    и риторика упиралась бы в 50 при любом накале просто потому, что её доля
    мала. Здесь каждая сторона меряется своей шкалой 0–100, где 50 — норма,
    и разрыв между ними осмыслен.

    None, если ни один блок стороны не измерен: разрыв с неизмеренной стороной
    не «ноль», а «неизвестно», и подставлять туда 50 значило бы утверждать
    норму там, где мы ничего не видели.
    """
    ws = {k: BLOCK_WEIGHTS[k] for k in blocks if k in block_z and k in BLOCK_WEIGHTS}
    total = sum(ws.values())
    full = sum(BLOCK_WEIGHTS[k] for k in blocks if k in BLOCK_WEIGHTS)
    # Сторона, измеренная меньше чем наполовину, не сторона.
    #
    # Поймано на живых данных: 19 августа кинетика не измерена (UCDP публикует
    # с задержкой), и «дела» схлопывались до одной дипломатии весом 0.15 из
    # 0.85. Россия с Украиной получали разрыв +38 и ярлык «угрозы без дел» —
    # посреди войны. Разрыв с полуизмеренной стороной не осторожен, он ложен.
    if not total or total < MIN_SIDE_SHARE * full:
        return None
    s = sum(w / total * max(-Z_CAP, min(Z_CAP, block_z[k])) for k, w in ws.items())
    return min(HEAT_MAX, 100.0 / (1.0 + math.exp(-s / scale)))


def heat(block_z: dict[str, float], scale: float = 1.6) -> float:
    """H = 100 * sigmoid(Σ w·z / scale). Раздел 4.1 методологии.

    scale — параметр калибровки, а не константа. При 1.6 шкала ложится так:
    z=0 -> 50, z=1 -> 65, z=2 -> 78, z=3 -> 87, z=4 -> 92. Начальное значение
    подобрано, чтобы одновременное отклонение всех пяти блоков на 3 MAD давало
    ~87, а не упиралось в потолок. Уточняется вместе с весами блоков в v0.2.
    """
    s = sum(BLOCK_WEIGHTS[k] * max(-Z_CAP, min(Z_CAP, v))
            for k, v in block_z.items() if k in BLOCK_WEIGHTS)
    return min(HEAT_MAX, 100.0 / (1.0 + math.exp(-s / scale)))


def data_coverage(indicators: dict[str, object]) -> float:
    """Доля индикаторов со свежими данными. Правило 6: нет данных ≠ нет риска."""
    if not indicators:
        return 0.0
    fresh = sum(1 for v in indicators.values() if v is not None)
    return 100.0 * fresh / len(indicators)


# Пороги темпа. Раздел 3 методологии, значения откалиброваны по замеру.
#
# В первой редакции стояли ΔH30 = ±8 и ΔH7 = +15 — числа, написанные до того,
# как появились данные. Замер на 22 000 наблюдений показал, что ±8 лежит за
# 99-м процентилем (срабатывает в 1.3% дней), а +15 не достигается ВООБЩЕ:
# ноль случаев за три года при 99-м процентиле ΔH7 = +5.0. Категория «Резкая
# эскалация» была недостижима по построению.
#
# Новые значения выбраны по доле дней, а не по красоте числа:
#   ±4 по ΔH30 -> 6.7% дней вне «Стабильно», то есть одна-две пары из двадцати
#      показывают движение в любой момент. Информативно и не шумно;
#   +5 по ΔH7  -> 1.0% дней. Достаточно редко, чтобы значить событие.
# Пересчитывать при смене шкалы накала: пороги привязаны к её масштабу.
TEMPO_D30 = 4.0
TEMPO_D7 = 5.0

# Насколько покрытие может отличаться, чтобы два дня считались сравнимыми.
# Единица — запас на округление, а не на смену состава блоков: уход целого
# блока меняет покрытие на 20 пунктов.
COV_TOLERANCE = 1.0


def tempo(h_now: float, h_7: float, h_30: float,
          phase: int, days_since_kinetic: int | None,
          cov_now: float | None = None, cov_7: float | None = None,
          cov_30: float | None = None) -> str | None:
    """Классификация темпа. None — сравнивать не с чем.

    СМЕНА ПОКРЫТИЯ НЕ ЕСТЬ ИЗМЕНЕНИЕ КОНФЛИКТА, и это здесь главное.

    Накал падает не только когда становится спокойнее, но и когда пропадает
    источник: блок уходит из расчёта, сумма весов уменьшается, число тянется
    к 50. Поймано на живых данных: 1 июля 2026 кончились кандидатские данные
    UCDP, покрытие Украины упало с 60% до 40%, накал — с 73.6 до 60.2. Темп
    прочитал бы это как «Разрядка» посреди войны. По всей базе таких дней
    среди сильных сигналов оказалось 28%.

    Поэтому сравнение делается ТОЛЬКО между днями с одинаковым покрытием.
    Иначе возвращается None: «не знаем» — честный ответ, а «Стабильно» было бы
    утверждением, которого мы сделать не можем.
    """
    d7, d30 = h_now - h_7, h_now - h_30
    same7 = cov_7 is None or cov_now is None or abs(cov_now - cov_7) <= COV_TOLERANCE
    same30 = cov_30 is None or cov_now is None or abs(cov_now - cov_30) <= COV_TOLERANCE

    # Скачок проверяется первым: недельное окно живее месячного, и резкая
    # эскалация не должна прятаться за спокойным месяцем.
    if same7 and d7 > TEMPO_D7:
        return "spike"
    if not same30:
        return None
    if phase >= 3 and abs(d30) <= TEMPO_D30 and (days_since_kinetic or 0) > 365:
        return "frozen"
    if d30 > TEMPO_D30:
        return "up"
    if d30 < -TEMPO_D30:
        return "down"
    return "flat"
