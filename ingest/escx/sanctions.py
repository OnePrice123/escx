"""Привязка санкционных программ к диадам.

Отдельный модуль ради одной вещи: таблица привязок — РЕДАКТОРСКОЕ решение, а
не выгрузка из источника. В файле OFAC страны нет вовсе, есть только программа,
и утверждение «эта программа относится к этому конфликту» делаем мы, а не
Минфин США. Такие утверждения обязаны лежать отдельно, правиться осознанно и
иметь ссылку на указ — иначе они расползаются по коду и через полгода никто не
вспомнит, почему венесуэльские меры приписаны спору об Эссекибо.
"""
from __future__ import annotations
import json
from pathlib import Path

CONFIG = Path(__file__).resolve().parent.parent / "config" / "sanctions_programs.json"


def load_program_map(path: Path | None = None) -> dict[str, set[str]]:
    """dyad_id -> множество кодов программ. Ключи на подчёркивание — комментарии."""
    p = path or CONFIG
    if not p.exists():
        return {}
    raw = json.loads(p.read_text(encoding="utf-8"))
    return {k: set(v.get("programs", []))
            for k, v in raw.items()
            if not k.startswith("_") and v.get("programs")}


def dyads_with_channel(path: Path | None = None) -> set[str]:
    """Диады, у которых санкционный канал вообще измеряется этим источником.

    Нужно ровно для того, чтобы у остальных экономический блок остался
    НЕ ИЗМЕРЕННЫМ, а не заполнился нулями. Ноль означал бы «мер не вводили»,
    и покрытие выросло бы до 40 % у всех при сигнале у трёх пар — ровно тот
    самообман, против которого покрытие и придумано.
    """
    return set(load_program_map(path))
