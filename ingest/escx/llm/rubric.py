"""Якорная рубрика: как заставить модель оценивать, а не фантазировать.

Разница между «оцени эскалацию от 0 до 100» и рубрикой ниже — это разница между
непроверяемым числом и воспроизводимой разметкой. Просьба поставить оценку по
широкой шкале без определений даёт результат, который не воспроизводится ни между
запусками, ни между моделями, ни между людьми — а значит, не может быть проверен
на согласие с ручной разметкой.

Поэтому: узкая порядковая шкала 0–4, каждая ступень описана наблюдаемым признаком,
и к каждой приложены примеры. Ровно так строят разметку для людей, и по той же
причине: чтобы два независимых разметчика сошлись.
"""
from __future__ import annotations

PROMPT_VERSION = "esc-extract-v3"   # входит в ключ кэша: смена промпта = новый прогон

ESCALATION_ANCHORS = {
    0: ("Нет эскалационного содержания",
        "Рутинная дипломатия, торговля, культура. Упоминание сторон без конфликтного контекста.",
        "«Министры обсудили расширение авиасообщения»"),
    1: ("Риторика",
        "Взаимные обвинения, протесты, вызов посла, отмена визита. Слова без действий.",
        "«МИД вызвал посла и заявил решительный протест»"),
    2: ("Институциональный или экономический шаг",
        "Санкции, экспортный контроль, разрыв соглашения, закрытие границы, высылка дипломатов.",
        "«Введены ограничения на экспорт двух товарных групп»"),
    3: ("Военные приготовления",
        "Учения у границы, переброска войск, мобилизация, повышение боеготовности, "
        "закрытие воздушного пространства или морского района.",
        "«Объявлены внеплановые учения в приграничном округе»"),
    4: ("Применение силы",
        "Зафиксированное вооружённое столкновение, удар, обстрел, захват, гибель людей "
        "в результате действий другой стороны.",
        "«В приграничном районе произошла перестрелка, есть погибшие»"),
}

# Обратная шкала: то, что гасит эскалацию. Отдельным полем, а не отрицательными
# значениями на той же шкале — потому что переговоры и обстрел могут произойти
# в один день, и это не «ноль», а два разных факта.
DEESCALATION_ANCHORS = {
    0: ("Нет", "Признаков деэскалации не обнаружено."),
    1: ("Сигнал", "Заявление о готовности к диалогу, смягчение риторики."),
    2: ("Процесс", "Объявлены переговоры, назначен посредник, восстановлены контакты."),
    3: ("Соглашение", "Подписано перемирие, снятие мер, обмен, отвод сил."),
}

SYSTEM = """Ты — разметчик новостных сообщений для системы мониторинга межгосударственных конфликтов.

Твоя задача — ИЗВЛЕКАТЬ наблюдаемые факты, а не оценивать ситуацию и не прогнозировать.

Жёсткие правила:
1. Всё, что ты утверждаешь, должно подтверждаться дословной цитатой из текста.
   Поле evidence обязательно и должно содержать фрагмент ИСХОДНОГО текста без изменений.
2. Если в тексте недостаточно сведений — ставь insufficient_evidence: true и null
   в спорных полях. Признать нехватку данных правильнее, чем угадать.
3. Не додумывай стороны конфликта. Если государство не названо прямо или через
   однозначное указание (столица, руководитель, официальное ведомство) — не указывай его.
4. Не оценивай вероятности, не прогнозируй развитие, не давай рекомендаций.
   Эти поля отсутствуют в схеме намеренно.
5. Ты размечаешь ТЕКСТ СООБЩЕНИЯ, а не реальность. Если издание пересказывает слух,
   отмечай это в reported_as: "rumor", а не повышай оценку.
6. Отвечай строго одним объектом JSON по схеме, без пояснений вокруг.
"""


def build_prompt(article: dict, dyad_hint: str | None = None) -> tuple[str, str]:
    """Возвращает (system, user). Промпт детерминирован — иначе кэш бессмыслен."""
    esc = "\n".join(
        f"  {k} — {v[0]}. {v[1]}\n      пример: {v[2]}"
        for k, v in sorted(ESCALATION_ANCHORS.items()))
    de = "\n".join(f"  {k} — {v[0]}. {v[1]}"
                   for k, v in sorted(DEESCALATION_ANCHORS.items()))
    hint = (f"\nПредполагаемая пара государств: {dyad_hint}. "
            "Подтверди или опровергни по тексту." if dyad_hint else "")

    user = f"""ШКАЛА ЭСКАЛАЦИИ (escalation_level), выбери ровно одну ступень:
{esc}

ШКАЛА ДЕЭСКАЛАЦИИ (deescalation_level), независимая от первой:
{de}

СХЕМА ОТВЕТА:
{{
  "actor_a": "ISO3 или null",
  "actor_b": "ISO3 или null",
  "escalation_level": 0-4,
  "deescalation_level": 0-3,
  "indicator_kind": "rhetoric|sanctions|treaty|mobilization|exercise|airspace|readiness|armed_incident|negotiation|other|none",
  "actor_is_state": true/false,
  "reported_as": "fact|claim|rumor",
  "evidence": "дословная цитата из текста",
  "insufficient_evidence": true/false
}}
{hint}

ТЕКСТ СООБЩЕНИЯ:
Заголовок: {article.get('title', '')}
Дата: {article.get('published_at', '')}
Текст: {article.get('body', article.get('snippet', ''))[:4000]}
"""
    return SYSTEM, user
